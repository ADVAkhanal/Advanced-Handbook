// Inlines handbook-infographics.{css,js} into Advanced_Handbook_Dashboard.html so the portal
// stays one self-contained, offline file. Safe to re-run: replaces the marked blocks.
//   node infographics/inline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const htmlPath = join(here, '..', 'Advanced_Handbook_Dashboard.html');
const css = readFileSync(join(here, 'handbook-infographics.css'), 'utf8').trim();
const js = readFileSync(join(here, 'handbook-infographics.js'), 'utf8').trim();
let html = readFileSync(htmlPath, 'utf8');

function block(name, body) {
  return `<!-- ${name}:START (generated by infographics/inline.mjs — edit the source file) -->\n${body}\n<!-- ${name}:END -->`;
}
function upsert(name, body, anchor) {
  const re = new RegExp(`<!-- ${name}:START[\\s\\S]*?<!-- ${name}:END -->`);
  const b = block(name, body);
  if (re.test(html)) { html = html.replace(re, () => b); return; }
  const at = html.indexOf(anchor);
  if (at < 0) throw new Error(`anchor not found: ${anchor}`);
  html = html.slice(0, at) + b + '\n' + html.slice(at);
}

upsert('HB-INFOGRAPHICS-CSS', `<style id="hb-infographics-css">\n${css}\n</style>`, '</head>');
upsert('HB-INFOGRAPHICS-JS', `<script id="hb-infographics-script">\n${js}\n</script>`, '<script id="app-logic-script">');
writeFileSync(htmlPath, html);
console.log(`inlined ${css.length} B css + ${js.length} B js -> ${htmlPath}`);
